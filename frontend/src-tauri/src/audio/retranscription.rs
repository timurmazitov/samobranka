    /// Spec D7, the same additive contract as the import progress payload:
    /// `code` (+ `params`) alongside the English `message`, omitted when the
    /// emitter has no code so the old payload shape is untouched.
    #[test]
    fn retranscription_progress_carries_code_and_params_additively() {
        let with_code = serde_json::to_value(RetranscriptionProgress {
            meeting_id: "m-1".to_string(),
            stage: "vad".to_string(),
            progress_percentage: 22,
            message: "Detecting speech segments... 40% (3 found)".to_string(),
            code: Some("detecting_segments_progress".to_string()),
            params: Some(serde_json::json!({ "percent": 40, "found": 3 })),
        })
        .unwrap();
        assert_eq!(with_code["meeting_id"], "m-1");
        assert_eq!(with_code["code"], "detecting_segments_progress");
        assert_eq!(with_code["params"]["percent"], 40);
        assert_eq!(with_code["params"]["found"], 3);
        assert_eq!(
            with_code["message"], "Detecting speech segments... 40% (3 found)",
            "the English prose stays as the diagnostic fallback"
        );

        let without_code = serde_json::to_value(RetranscriptionProgress {
            meeting_id: "m-1".to_string(),
            stage: "decoding".to_string(),
            progress_percentage: 5,
            message: "Decoding audio file...".to_string(),
            code: None,
            params: None,
        })
        .unwrap();
        assert!(
            without_code.get("code").is_none(),
            "an un-coded payload keeps the pre-i18n shape"
        );
        assert!(without_code.get("params").is_none());
    }

    #[test]
    fn test_create_transcript_segments_empty() {
        let transcripts: Vec<(String, f64, f64)> = vec![];
        let segments = create_transcript_segments(&transcripts);
        assert!(segments.is_empty());
    }

    #[test]
    fn test_create_transcript_segments_single() {
        let transcripts = vec![
            ("Hello world".to_string(), 0.0, 1500.0), // 0-1.5 seconds
        ];
        let segments = create_transcript_segments(&transcripts);

        assert_eq!(segments.len(), 1);
        assert_eq!(segments[0].text, "Hello world");
        assert_eq!(segments[0].audio_start_time, Some(0.0));
        assert_eq!(segments[0].audio_end_time, Some(1.5));
        assert_eq!(segments[0].duration, Some(1.5));
    }

    #[test]
    fn test_create_transcript_segments_multiple() {
        let transcripts = vec![
            ("First segment".to_string(), 0.0, 2000.0), // 0-2 seconds
            ("Second segment".to_string(), 3000.0, 5000.0), // 3-5 seconds
            ("Third segment".to_string(), 6500.0, 8000.0), // 6.5-8 seconds
        ];
        let segments = create_transcript_segments(&transcripts);

        assert_eq!(segments.len(), 3);

        // First segment
        assert_eq!(segments[0].text, "First segment");
        assert_eq!(segments[0].audio_start_time, Some(0.0));
        assert_eq!(segments[0].audio_end_time, Some(2.0));
        assert_eq!(segments[0].duration, Some(2.0));

        // Second segment
        assert_eq!(segments[1].text, "Second segment");
        assert_eq!(segments[1].audio_start_time, Some(3.0));
        assert_eq!(segments[1].audio_end_time, Some(5.0));
        assert_eq!(segments[1].duration, Some(2.0));

        // Third segment
        assert_eq!(segments[2].text, "Third segment");
        assert_eq!(segments[2].audio_start_time, Some(6.5));
        assert_eq!(segments[2].audio_end_time, Some(8.0));
        assert_eq!(segments[2].duration, Some(1.5));
    }

    #[test]
    fn test_create_transcript_segments_trims_whitespace() {
        let transcripts = vec![("  Hello with spaces  ".to_string(), 0.0, 1000.0)];
        let segments = create_transcript_segments(&transcripts);

        assert_eq!(segments.len(), 1);
        assert_eq!(segments[0].text, "Hello with spaces");
    }

    #[test]
    fn test_create_transcript_segments_generates_unique_ids() {
        let transcripts = vec![
            ("Segment one".to_string(), 0.0, 1000.0),
            ("Segment two".to_string(), 1000.0, 2000.0),
        ];
        let segments = create_transcript_segments(&transcripts);

        assert_eq!(segments.len(), 2);
        assert_ne!(segments[0].id, segments[1].id);
        assert!(segments[0].id.starts_with("transcript-"));
        assert!(segments[1].id.starts_with("transcript-"));
    }

    #[test]
    fn test_cancellation_flag() {
        // Reset flag to known state
        RETRANSCRIPTION_CANCELLED.store(false, Ordering::SeqCst);
        RETRANSCRIPTION_IN_PROGRESS.store(false, Ordering::SeqCst);

        assert!(!is_retranscription_in_progress());

        // Test cancellation
        cancel_retranscription();
        assert!(RETRANSCRIPTION_CANCELLED.load(Ordering::SeqCst));

        // Reset for other tests
        RETRANSCRIPTION_CANCELLED.store(false, Ordering::SeqCst);
    }

    #[test]
    fn test_vad_redemption_time_constant() {
        // Batch processing uses 2000ms to bridge natural pauses in full-file VAD
        assert_eq!(VAD_REDEMPTION_TIME_MS, 2000);
    }

    /// The scale itself (the segment ramp, the save milestone, the band) is
    /// shared and pinned once in `audio::progress_scale`. What stays here is
    /// the retranscription bar's own contract: its milestones are emitted
    /// *through* that same scale as the import bar's, so the last native
    /// value never crosses into the band the frontend fills from the pass
    /// state.
    #[test]
    fn the_retranscription_bar_stops_at_the_diarization_band() {
        assert_eq!(SAVING_PROGRESS, 70);
        assert_eq!(DIARIZATION_BAND_START, 75);
        assert!(SAVING_PROGRESS < DIARIZATION_BAND_START);
    }

